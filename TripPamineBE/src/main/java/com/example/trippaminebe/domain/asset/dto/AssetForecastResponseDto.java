package com.example.trippaminebe.domain.asset.dto;

import lombok.AllArgsConstructor;
import lombok.Getter;

import java.time.LocalDate;


/**
 * =========================================================
 * 미래 자산 시뮬레이션 Response DTO
 * =========================================================
 *
 * 현재 자산과 최근 수입/지출 데이터를 이용해서
 *
 * - 월 예상 저축액
 * - 3개월 후 예상 자산
 * - 6개월 후 예상 자산
 * - 12개월 후 예상 자산
 * - 여행 목표 달성 예상 기간
 *
 * 을 프론트엔드에 전달한다.
 */
@Getter
@AllArgsConstructor
public class AssetForecastResponseDto {


    // =====================================================
    // 현재 자산
    // =====================================================

    private Long currentAsset;


    // =====================================================
    // 최근 평균 수입 / 지출
    // =====================================================

    private Long averageMonthlyIncome;

    private Long averageMonthlyExpense;


    // =====================================================
    // 월 예상 저축 가능 금액
    //
    // 평균 월 수입 - 평균 월 지출
    // =====================================================

    private Long monthlySaving;


    // =====================================================
    // 미래 예상 자산
    // =====================================================

    private Long after3Months;

    private Long after6Months;

    private Long after12Months;


    // =====================================================
    // 대표 목표 정보
    // =====================================================

    private Long goalId;

    private String goalName;

    private Long goalTargetAmount;

    private Long goalCurrentAmount;


    // =====================================================
    // 목표까지 남은 금액
    // =====================================================

    private Long goalRemainingAmount;


    // =====================================================
    // 목표 달성까지 예상 개월 수
    //
    // 예:
    // 3 -> 약 3개월 후
    //
    // 저축액이 0 이하라서 계산할 수 없으면 null
    // =====================================================

    private Integer monthsToGoal;


    // =====================================================
    // 예상 목표 달성 날짜
    //
    // 예:
    // 2027-01-19
    //
    // 계산할 수 없으면 null
    // =====================================================

    private LocalDate expectedGoalDate;


    // =====================================================
    // 간단한 분석 메시지
    // =====================================================

    private String forecastMessage;
}